"""位图映射协议 - 5x5局部区域到32位寄存器的映射"""

# Bit索引 → (dx, dy) 偏移量
# 按照协议V2.1：Bit0~Bit4 对应 Y+2 行，Bit5~Bit9 对应 Y+1 行，以此类推
BMAP_OFFSETS: list[tuple[int, int]] = [
    # Bit0~Bit4: Y+2 行（从右到左）
    (+2, +2), (+1, +2), (0, +2), (-1, +2), (-2, +2),
    # Bit5~Bit9: Y+1 行
    (+2, +1), (+1, +1), (0, +1), (-1, +1), (-2, +1),
    # Bit10~Bit14: Y0 行
    (+2, 0), (+1, 0), (0, 0), (-1, 0), (-2, 0),
    # Bit15~Bit19: Y-1 行
    (+2, -1), (+1, -1), (0, -1), (-1, -1), (-2, -1),
    # Bit20~Bit24: Y-2 行
    (+2, -2), (+1, -2), (0, -2), (-1, -2), (-2, -2),
]

BMAP_MASK: int = 0x01FFFFFF  # 低25位掩码
BMAP_BITS: int = 25          # 有效位数
BMAP_RADIUS: int = 2         # 5x5区域半径
